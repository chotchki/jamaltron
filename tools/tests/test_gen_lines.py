def test_the_ruled_long_rows_may_stay_long_and_nothing_else_may(monkeypatch):
    monkeypatch.setattr(g, "ALLOW_REPEAT", ())
    monkeypatch.setattr(g, "OVER_CAP_RULED", {"flopping.38": 61})
