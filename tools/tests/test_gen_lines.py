def extracts(tmp_path, book7="", book8=""):
    (tmp_path / "book7_jamal.txt").write_text(book7, encoding="utf-8")
    (tmp_path / "book8_jamal.txt").write_text(book8, encoding="utf-8")
    return tmp_path


def test_a_verbatim_line_not_in_its_book_is_a_fabrication(tmp_path):
    ex = extracts(tmp_path, book7="... Jamal is very excited about this, he said ...")
    ok = one(row("built.01", "Jamal is very excited about this", source="verbatim", bk="7"))
    _, _, _, notes = g.build(ok, ex)
    assert any("checked against the extracts" in n for n in notes)
    bad = one(row("built.01", "Jamal is very excited about that", source="verbatim", bk="7"))
    assert "fabrication" in errors_of(bad, ex)


def test_the_book_quote_behind_an_adapted_row_is_checked_too(tmp_path):
    ex = extracts(tmp_path, book8="Mister Carl, Jamal is sorry.")
    good = 'ORIGINAL: "Mister Carl, Jamal is sorry."'
    g.build(one(row("built.01", "Mr. Engineer, Jamal is sorry.", source="adapted", bk="8",
                    note=good)), ex)
    bad = 'ORIGINAL: "Mister Donut, Jamal is sorry."'
    assert "NOT in book 8" in errors_of(one(row("built.01", "Mr. Engineer, Jamal is sorry.",
                                                source="adapted", bk="8", note=bad)), ex)


